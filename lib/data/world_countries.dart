/// World sovereign-country calling-code catalog (UN 193 + Holy See + Palestine).
/// E.164 codes and NANP area codes are adapted from country-codes-list (MIT);
/// names are CLDR territory translations via Babel. Territory dependencies are
/// intentionally omitted so the list remains a 195-country sovereign catalog.
class WorldCountry {
  const WorldCountry({
    required this.isoCode,
    required this.dialCode,
    required this.localizedNames,
    this.areaCodes = const <String>[],
    this.aliases = const <String>[],
  });

  final String isoCode;
  final String dialCode;
  final Map<String, String> localizedNames;
  final List<String> areaCodes;
  final List<String> aliases;

  String get flag =>
      String.fromCharCodes(isoCode.codeUnits.map((unit) => unit + 127397));

  String nameFor(AppLanguage language) =>
      localizedNames[language.locale.languageCode] ?? localizedNames['en']!;

  bool matches(String rawQuery) {
    final query = rawQuery.trim().toLowerCase();
    if (query.isEmpty) return true;
    final digits = query.replaceAll(RegExp(r'\D'), '');
    return isoCode.toLowerCase().contains(query) ||
        dialCode.contains(query) ||
        (digits.isNotEmpty && dialCode.replaceAll('+', '').contains(digits)) ||
        localizedNames.values.any(
          (name) => name.toLowerCase().contains(query),
        ) ||
        aliases.any((name) => name.toLowerCase().contains(query));
  }
}

